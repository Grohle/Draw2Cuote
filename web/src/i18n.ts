export type Textos = typeof TEXTOS_ES;

export function obtenerTextos(idioma: Idioma): Textos {
  return idioma === 'en' ? TEXTOS_EN : TEXTOS_ES;
}

const CLAVE_STORAGE_IDIOMA = 'draw2quote.idioma';

export function cargarIdioma(): Idioma {
  const guardado = localStorage.getItem(CLAVE_STORAGE_IDIOMA);
  if (guardado === 'en' || guardado === 'es') return guardado;
  // por defecto, detecta del navegador; si no es español, usa inglés
  return navigator.language?.toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function guardarIdioma(idioma: Idioma): void {
  localStorage.setItem(CLAVE_STORAGE_IDIOMA, idioma);
}
